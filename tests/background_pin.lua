vim.opt.rtp:prepend(vim.fn.getcwd())
local reader = require('moyu')
local stealth = require('moyu.stealth')
local root = vim.fn.stdpath('data') .. '/project'
vim.fn.mkdir(root .. '/.git', 'p')
local code, paragraphs = {}, {}
for index = 1, 100 do
  code[index] = 'local value = ' .. index
  paragraphs[index] = '正文 ' .. index
end
local a, b, c, book = root .. '/a.lua', root .. '/b.lua', root .. '/c.lua', root .. '/book.txt'
for _, path in ipairs({ a, b, c }) do vim.fn.writefile(code, path) end
vim.fn.writefile(paragraphs, book)
vim.cmd('edit ' .. vim.fn.fnameescape(a))
local original = vim.api.nvim_get_current_buf()
local loaded = vim.fn.bufadd(b)
vim.fn.bufload(loaded)
vim.bo[loaded].buflisted = true
local global_calls, local_calls = 0, 0
vim.keymap.set('n', '<F4>', function() global_calls = global_calls + 1 end)
vim.keymap.set('n', '<F4>', function() local_calls = local_calls + 1 end, { buffer = loaded, desc = 'original F4' })
local function press(key)
  vim.api.nvim_feedkeys(vim.api.nvim_replace_termcodes(key, true, false, true), 'xt', false)
end
local function saved_line()
  local state = vim.json.decode(table.concat(vim.fn.readfile(vim.fn.stdpath('data') .. '/moyu/progress.json'), '\n'))
  return state.books[book].line
end
assert(stealth.toggle_background_pin() == nil, 'pinning must be inactive outside Moyu Mode')
press('<F4>')
assert(global_calls == 1)
reader.stealth(book)
press('j')
assert(vim.api.nvim_get_current_buf() == loaded and saved_line() == 5)
local view = vim.fn.winsaveview()
press('ab<F4>')
assert(vim.api.nvim_get_current_buf() == loaded and saved_line() == 5, 'pinning must not change file or book progress')
assert(vim.deep_equal(view, vim.fn.winsaveview()), 'pinning must not move the code viewport')
press('c')
assert(saved_line() == 5, 'pinning should reset partial typing counts')
press('de')
assert(saved_line() == 9 and vim.api.nvim_get_current_buf() == loaded, 'typed advancement must keep the pinned file')
press('jk')
assert(saved_line() == 9 and vim.api.nvim_get_current_buf() == loaded, 'forward and backward navigation must keep the pin')
press('<F3>+-j')
assert(saved_line() == 13 and vim.api.nvim_get_current_buf() == loaded, 'layout and line-count changes must keep the pin')
press('<F4>')
assert(saved_line() == 13 and vim.api.nvim_get_current_buf() == loaded, 'unpinning must take effect on the next segment')
press('j')
local temporary = vim.api.nvim_get_current_buf()
assert(vim.api.nvim_buf_get_name(temporary) == c and saved_line() == 17, 'unpinning should resume file rotation')
press('<F4>j')
assert(vim.api.nvim_get_current_buf() == temporary and saved_line() == 21, 'pin mapping must follow background switches')
press('<Esc>')
assert(vim.api.nvim_get_current_buf() == original and not reader.is_active())
assert(not vim.api.nvim_buf_is_valid(temporary), 'exit must still clean up a pinned temporary file')
press('<F4>')
assert(global_calls == 2 and local_calls == 0, 'outside mode the original global mapping must work')
local maps = vim.api.nvim_buf_get_keymap(loaded, 'n')
assert(#maps == 1 and maps[1].desc == 'original F4', 'background switches must restore the original local mapping')
reader.toggle()
press('j')
assert(vim.api.nvim_get_current_buf() == loaded, 'a new session must start unpinned')
press('<F4>')
vim.api.nvim_exec_autocmds('FocusLost', {})
assert(not reader.is_active() and vim.api.nvim_get_current_buf() == original)
reader.toggle()
press('j')
assert(vim.api.nvim_get_current_buf() == loaded, 'auto-hide must clear the previous session pin')
reader.close()
reader.setup({ stealth = { background = false } })
reader.toggle()
assert(stealth.toggle_background_pin() == nil, 'pinning must not enable rotation disabled in configuration')
press('j')
assert(vim.api.nvim_get_current_buf() == original)
reader.close()
reader.open(book)
press('<F4>')
assert(global_calls == 3 and not stealth.active(), 'floating reading must not install the pin shortcut')
reader.close()
assert(vim.deep_equal(code, vim.fn.readfile(a)) and vim.deep_equal(code, vim.fn.readfile(b)))
print('PASS: 固定背景、正文推进、取消固定、跨文件映射、退出恢复及会话隔离')
vim.cmd('qa!')
